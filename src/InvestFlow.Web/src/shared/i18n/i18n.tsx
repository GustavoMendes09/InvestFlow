const translations: Record<Language, Record<TranslationKey, string>> = {
  en: english,
  'pt-BR': portuguese,
}

const STORAGE_KEY = 'investflow-language'

function getInitialLanguage(): Language {
  const savedLanguage = window.localStorage.getItem(STORAGE_KEY)
  if (savedLanguage === 'en' || savedLanguage === 'pt-BR') return savedLanguage
  return window.navigator.language.toLowerCase().startsWith('pt') ? 'pt-BR' : 'en'
}

function interpolate(template: string, values?: Record<string, string | number>): string {
  if (!values) return template
  return Object.entries(values).reduce(
    (result, [key, value]) => result.replaceAll(`{{${key}}}`, String(value)),
    template,
  )
}

interface I18nContextValue {
  language: Language
  locale: 'en-AU' | 'pt-BR'
  setLanguage: (language: Language) => void
  t: (key: TranslationKey, values?: Record<string, string | number>) => string
}

const defaultContext: I18nContextValue = {
  language: 'en',
  locale: 'en-AU',
  setLanguage: () => undefined,
  t: (key, values) => interpolate(english[key], values),
}

const I18nContext = createContext<I18nContextValue>(defaultContext)

export function I18nProvider({ children }: { children: ReactNode }) {
  const [language, setLanguage] = useState<Language>(getInitialLanguage)

  useEffect(() => {
    window.localStorage.setItem(STORAGE_KEY, language)
    document.documentElement.lang = language
    document.title = language === 'pt-BR'
      ? 'InvestFlow — Seu dinheiro em foco'
      : 'InvestFlow — Your money, in focus'
  }, [language])

  const value = useMemo<I18nContextValue>(() => ({
    language,
    locale: language === 'pt-BR' ? 'pt-BR' : 'en-AU',
    setLanguage,
    t: (key, values) => interpolate(translations[language][key], values),
  }), [language])

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useI18n() {
  return useContext(I18nContext)
}
